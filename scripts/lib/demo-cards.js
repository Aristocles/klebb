// Pure, deterministic generators for the demo seed. Consumed by:
//   - scripts/seed-demo.js (the CLI/auto-seed entrypoint)
//   - tests/seed-demo.test.js (verifies generated output)
//
// Every `buildXxx()` function returns a valid klebb.datafile.v1 manifest
// object. The set of dates generated is anchored to a "today" reference
// passed in — the caller decides whether that's `new Date()` (live seed)
// or a fixed date (reproducible tests).
//
// Random values are generated by a seeded PRNG so identical inputs produce
// identical output. This makes the seed deterministic per install date
// (useful: tests are stable; visually the data always looks the same if
// you re-seed on the same day).

'use strict';

// ---------------------------------------------------------------------------
// Seeded PRNG — mulberry32, good-enough for demo data. Deterministic,
// reproducible, no external dependency.
// ---------------------------------------------------------------------------
function makeRng(seed) {
  let a = seed >>> 0;
  return function() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function rngInt(rng, min, max) {
  return Math.floor(rng() * (max - min + 1)) + min;
}

function rngFloat(rng, min, max) {
  return rng() * (max - min) + min;
}

function rngPick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

// ---------------------------------------------------------------------------
// Date helpers
// ---------------------------------------------------------------------------
function iso(d) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

function addDays(d, n) {
  const out = new Date(d);
  out.setDate(out.getDate() + n);
  return out;
}

// Last N days ending at `today`, oldest first.
function lastNDays(today, n) {
  const out = [];
  for (let i = n - 1; i >= 0; i--) out.push(addDays(today, -i));
  return out;
}

function utcIso(d, hour) {
  const h = hour ?? 8;
  const dt = new Date(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate(), h, 0, 0));
  return dt.toISOString();
}

