// Top-level generator — returns { cards: { filename: object, ... } }
// ---------------------------------------------------------------------------
function generateDemoCards({ today, seed } = {}) {
  const ref = today instanceof Date ? today : new Date();
  // Strip time — we want a pure date anchor.
  const refDate = new Date(ref.getFullYear(), ref.getMonth(), ref.getDate());
  const rngSeed = Number.isInteger(seed) ? seed : 0xc0ffee;
  const rng = makeRng(rngSeed);

  return {
    'welcome.json': buildWelcome(),
    'how-to-add-a-card.json': buildHowToAddACard(),
    'weight.json': buildWeight(refDate, rng),
    'bp.json': buildBP(refDate, rng),
    'mood.json': buildMood(refDate, rng),
    'sleep-hours.json': buildSleepHours(refDate, rng),
    'hydration.json': buildHydration(refDate, rng),
    'steps.json': buildSteps(refDate, rng),
    'caffeine.json': buildCaffeine(refDate, rng),
    'energy.json': buildEnergy(refDate, rng),
    'heart-rate-resting.json': buildRestingHR(refDate, rng),
    'reflections.json': buildReflections(refDate, rng),
    'symptoms.json': buildSymptoms(refDate),
    'medications.json': buildMedications(refDate, rng),
    'habits.json': buildHabits(refDate, rng)
  };
}

